const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require('typescript');
const cache = new Map();
function load(file) {
  file = path.resolve(file); if(cache.has(file)) return cache.get(file);
  const exports = {}; cache.set(file,exports);
  vm.runInNewContext(ts.transpileModule(fs.readFileSync(file,'utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText,{exports,require: name => load(path.resolve(path.dirname(file),name+'.ts'))});
  return exports;
}
const {buildRoutine, findSlotRun} = load('src/operationalAgenda.ts');
const {dayItems,summarizeDay,projectDay} = load('src/dayCalendar.ts');
const {kpiCompliance,kpiPeriod} = load('src/kpiMetrics.ts');
const employee={id:'010',name:'Celina',role:'JEFE_AREA',branch:'Matriz'};
const cleaning={branch:'Matriz',activity:'Barrer frente',start:'09:00',end:'09:30',details:'Limpiar frente',assignments:{Lunes:'Celina'}};
const base={id:'daily',name:'Aseo asignado',area:'Aseo',start:'09:00',end:'09:30',durationMinutes:30,ownerRoles:['JEFE_AREA'],employeeIds:['010'],branch:'Matriz',evidence:'photo'};
const mixed={...base,id:'display',name:'Aseo y exhibición',area:'Aseo y exhibición'};
const slots=buildRoutine(employee,[base,mixed],[cleaning],'Matriz','2026-09-28');
assert.equal(slots.length,2,'daily cleaning and its SLA must be one obligation; mixed activity is retained');
assert.equal(slots.find(s=>s.kind==='Aseo').evidence,'photo');
assert.equal(buildRoutine(employee,[base],[cleaning],'Sucursal Centro','2026-09-28').length,0);
assert.equal(buildRoutine(employee,[{...base,employeeIds:['999']}],[],'Matriz','2026-09-28').length,0,'do not assign another employee’s targeted schedule');
const slot=slots.find(s=>s.kind==='Aseo');
const run={id:'r',employeeId:'010',date:'2026-09-28',itemType:'Actividad',itemId:'daily',title:'Aseo asignado',scheduledStart:'09:00',scheduledEnd:'09:30',slaMinutes:30,evidence:'photo',startedAt:'2026-09-28T15:00:00Z',completedAt:'2026-09-28T16:00:00Z',pausedMinutes:35,status:'Completada',beforeEvidenceCapture:{},afterEvidenceCapture:{}};
assert.equal(findSlotRun(slot,[run]).id,'r','old alias evidence must remain accessible');
const plan={employee_number:'010',day:'2026-09-28',branch:'Matriz',slots:[slot]};
let items=dayItems(plan.day,'010',plan,[run],[],[]);
assert.equal(items.length,1,'no duplicate from alias');
assert.equal(summarizeDay(plan.day,'2026-09-29','12:00',items,true).color,'green','priority pause discounted');
