assert.equal(summarizeDay(plan.day,'2026-09-29','12:00',items,true).color,'red');
items=dayItems(plan.day,'010',plan,[{...run,pausedMinutes:0}],[],[]);
assert.equal(summarizeDay(plan.day,'2026-09-29','12:00',items,true).color,'yellow');
const centroSlot={...slot,key:'Centro-aseo-1',kind:'Centro',itemId:'aseo-1'};
