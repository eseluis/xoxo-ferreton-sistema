const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const assert = require('node:assert/strict');
function load(path) { const exports = {}; vm.runInNewContext(ts.transpileModule(fs.readFileSync(path, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText, { exports }); return exports; }
const { buildCentroAgenda, CENTRO_TASKS, centroCompletionError, centroSummary, isCentroSupervisor, cleaningFor } = load('src/centroOperation.ts');
const { activeMinutes, resumePriority } = load('src/priorityPause.ts');
const day = '2026-09-22';
const worker = (id, role = 'AUXILIAR', overrides = {}) => ({ id, name: id, role, roleLabel: role, start: '08:50', end: '18:00', present: true, arrived: true, ...overrides });
const record = (task_id, owner_id, status = 'En curso', data = {}) => ({ day, task_id, owner_id, status, data, version: 1, history: [], updated_at: '' });
let agenda = buildCentroAgenda(day, [worker('a'), worker('b')], [], '10:00');
assert.equal(agenda.length, CENTRO_TASKS.length);
assert.equal(new Set(agenda.filter(t => t.inventory).map(t => t.ownerId)).size, 2);
assert.ok(agenda.filter(t => t.outdoor).every(t => !t.digital));
agenda = buildCentroAgenda(day, [worker('a')], [], '10:00');
assert.ok(agenda.every(t => t.ownerId === 'a'));
assert.ok(agenda.filter(t => t.outdoor).every(t => t.digital));
agenda = buildCentroAgenda(day, [worker('a'), worker('g', 'GERENTE_TIENDA')], [], '10:00');
assert.equal(agenda.find(t => t.id === 'apertura').ownerId, 'g');
assert.ok(agenda.filter(t => t.ownerId === 'a' && !t.control).length > agenda.filter(t => t.ownerId === 'g' && !t.control).length);
const prior = record('inventario-1', 'a', 'En curso', { items: [{code:'123'}] });
agenda = buildCentroAgenda(day, [worker('a', 'AUXILIAR', { present: false }), worker('b')], [prior], '10:30');
assert.equal(agenda.find(t => t.id === prior.task_id).ownerId, 'b');
assert.equal(agenda.find(t => t.id === prior.task_id).record.data.items[0].code, '123');
agenda = buildCentroAgenda(day, [worker('a'), worker('b')], [prior], '10:30');
assert.equal(agenda.find(t => t.id === prior.task_id).ownerId, 'a');
agenda = buildCentroAgenda(day, [worker('a', 'AUXILIAR', { end: '12:00' })], [], '10:30');
assert.equal(agenda.find(t => t.id === 'cierre').ownerId, undefined);
agenda = buildCentroAgenda(day, [worker('late', 'AUXILIAR', { start: '13:00' })], [prior], '14:00');
assert.equal(agenda.find(t => t.id === 'inventario-1').ownerId, 'late');
agenda = buildCentroAgenda(day, [worker('a', 'AUXILIAR', { present: false })], [], '13:00');
assert.ok(agenda.every(t => !t.ownerId));
agenda = buildCentroAgenda(day, [worker('a'), worker('b')], [record('trafico-1', 'a', 'En curso', {mode:'Exterior'})], '12:00');
assert.ok(agenda.find(t => t.id === 'trafico-2').blocked);
assert.equal(isCentroSupervisor({id:'003',role:'AUXILIAR'}),true);
assert.equal(isCentroSupervisor({id:'006',role:'JEFE_AREA'}),false);
assert.notEqual(cleaningFor(day,1),cleaningFor('2026-09-23',1));
const inventory = CENTRO_TASKS.find(t => t.id === 'inventario-1');
assert.match(centroCompletionError(inventory, {}),/25/);
const items = Array.from({length:25},(_,i)=>({code:String(i),description:'Producto',physical:1,system:1,price:10,location:'A1',label:true,registered:true,result:'Correcto',correction:'',evidence:''}));
assert.equal(centroCompletionError(inventory,{items}),undefined);
assert.match(centroCompletionError(inventory,{items},[record('inventario-2','b','En curso',{items:[items[0]]})]),/duplicados/);
assert.match(centroCompletionError(inventory,{items:[...items.slice(1),{...items[0],result:'Diferencia inventario'}]}),/evidencia/);
const summary = centroSummary([record('atencion','a','En curso',{visitantes:50,compradores:10,ventas:1000,tickets:10})]);
assert.equal(summary.conversion,20); assert.equal(summary.averageTicket,100);
const clock={startedAt:'2026-09-22T15:00:00Z',pausedAt:'2026-09-22T15:10:00Z',pauseReason:'Cliente'};
assert.equal(activeMinutes(clock,Date.parse('2026-09-22T16:00:00Z')),10);
assert.equal(activeMinutes(resumePriority(clock,'2026-09-22T15:50:00Z'),Date.parse('2026-09-22T16:00:00Z')),20);
console.log('PASS: Centro roles, coverage, transfers, reduced mode, inventory, metrics and priority pause clocks');
