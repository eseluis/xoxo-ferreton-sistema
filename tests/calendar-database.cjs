const fs=require('node:fs');
const assert=require('node:assert/strict');
const {PGlite}=require('@electric-sql/pglite');
(async()=>{
  const db=new PGlite();
  await db.exec(`create role anon; create role authenticated; create schema auth;
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('test.user',true),'')::uuid $$;
    create table profiles(user_id uuid,employee_number text,branch text,active boolean);
    create table app_state(key text,value jsonb);
    create table centro_operation_records(day date,task_id text,owner_id text,status text,data jsonb);
    create function current_profile() returns profiles language sql stable security definer set search_path=public as $$ select p from profiles p where user_id=auth.uid() and active limit 1 $$;
    create function can_manage_all() returns boolean language sql stable as $$ select coalesce((current_profile()).employee_number='003',false) $$;
    create function can_manage_branch(b text) returns boolean language sql stable as $$ select can_manage_all() $$;
    grant usage on schema public,auth to authenticated; grant select on app_state to authenticated;
    insert into profiles values('00000000-0000-0000-0000-000000000010','010','Matriz',true),('00000000-0000-0000-0000-000000000011','011','Matriz',true),('00000000-0000-0000-0000-000000000003','003','Matriz',true);
  `);
  const migration=fs.readFileSync('supabase-operation-calendar.sql','utf8');
  await db.exec(migration); await db.exec(migration);
  const who=async n=>db.exec(`reset role; select set_config('test.user','00000000-0000-0000-0000-${String(n).padStart(12,'0')}',false); set role authenticated;`);
  await who(10);
  await db.exec(`insert into operation_day_plans(employee_number,day,branch,slots) values('010',(now() at time zone 'America/Mexico_City')::date,'Matriz','[]');`);
  await db.exec(`insert into operation_day_plans(employee_number,day,branch,slots) values('010',(now() at time zone 'America/Mexico_City')::date,'Matriz','[]') on conflict(employee_number,day) do nothing;`);
  await assert.rejects(()=>db.exec(`insert into operation_day_plans values('011',(now() at time zone 'America/Mexico_City')::date,'Matriz','[]',now());`),/policy/);
  await assert.rejects(()=>db.exec(`insert into operation_day_plans values('010',(now() at time zone 'America/Mexico_City')::date-1,'Matriz','[]',now());`),/policy/);
  await assert.rejects(()=>db.exec(`update operation_day_plans set slots='[]';`),/permission/);
  await assert.rejects(()=>db.exec(`select operation_calendar_centro(current_date,current_date,'011');`),/permiso/);
  await db.exec(`update operation_project_config set start_day='2030-01-01';`);
  assert.equal((await db.query('select start_day::text from operation_project_config')).rows[0].start_day,'2026-10-01');
  await who(11); assert.equal((await db.query('select * from operation_day_plans')).rows.length,0);
  await who(3); assert.equal((await db.query('select * from operation_day_plans')).rows.length,1);
  await db.exec(`update operation_project_config set start_day='2026-10-02';`);
  assert.equal((await db.query('select start_day::text from operation_project_config')).rows[0].start_day,'2026-10-02');
  await assert.rejects(()=>db.exec(`select operation_calendar_centro(current_date,current_date+63,'010');`),/Periodo/);
  await db.exec('reset role; set role anon;');
  await assert.rejects(()=>db.exec('select * from operation_day_plans'),/permission/);
  await db.close(); console.log('PASS: calendar migration reapplies, snapshots are immutable, own/team permissions, project configuration and range limit');
})().catch(e=>{console.error(e);process.exitCode=1;});
